//! End-to-end Retry cost over loopback UDP
//!
//! `retry_e2e client <mode> <workers> <empty|bogus> <window>` spawns `retry_e2e server` as a
//! child process, checks that a real client completes a Retry handshake, then sends `window`
//! unique Initials at a time and waits for all their Retries (closed loop, no losses allowed).
//! The server reports its own CPU time (user + sys, so including socket syscalls) over stdin/
//! stdout, which gives server CPU per Initial independently of the client's cost.
//!
//! Modes: `manual` (the application calls `Incoming::retry()`), `fast` (an `InitialFilter`
//! returns `Retry`), with `-mac` for authenticated tokens. Only `manual` exists without the
//! `filter` feature, i.e. on the baseline.
//!
//! Environment: `RETRY_E2E_N` requests per sample (default 32768), `RETRY_E2E_RCVBUF_KB` socket
//! receive buffers (default 256), `RETRY_E2E_SERVER_WRAP` a command prefix for the server
//! process, e.g. `taskset -c 2,3`.
//!
//! Two hosts: `retry_e2e server <mode> <workers> <bind address>` runs a server by itself and
//! prints its CPU use every second. `retry_e2e flood <server address> <empty|bogus|bogus-mac>
//! <rate in k/s>...` sends unique Initials at each rate for `RETRY_E2E_STEP_SECS` (default 5) from
//! `RETRY_E2E_THREADS` sockets (default 4), and counts the Retries that come back.

use std::{
    collections::HashMap,
    io::{BufRead, BufReader, Write},
    net::{SocketAddr, ToSocketAddrs, UdpSocket},
    process::{Command, Stdio},
    sync::{
        Arc,
        atomic::{AtomicBool, AtomicU64, Ordering},
    },
    thread,
    time::{Duration, Instant},
};

use rustls::pki_types::{CertificateDer, PrivatePkcs8KeyDer};

const CORPUS: usize = 2048;
const SAMPLES: usize = 9;
/// Unique Initials per flood, so a repeat never meets a still-queued `Incoming` with its CID
const FLOOD_CORPUS: usize = 65536;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    match args[1].as_str() {
        "server" => server(
            &args[2],
            args[3].parse().unwrap(),
            args.get(4).map_or("127.0.0.1:0", |a| a.as_str()),
        ),
        "client" => client(
            &args[2],
            args[3].parse().unwrap(),
            &args[4],
            args[5].parse().unwrap(),
        ),
        "flood" => flood(&args[2], &args[3], &args[4..]),
        other => panic!("unknown command {other}"),
    }
}

fn mac(mode: &str) -> bool {
    mode.ends_with("-mac")
}

/// Certificate and key, generated by the client and passed to the server in the environment
fn cert() -> (CertificateDer<'static>, PrivatePkcs8KeyDer<'static>) {
    let hex = |name| -> Vec<u8> {
        let s = std::env::var(name).unwrap();
        (0..s.len())
            .step_by(2)
            .map(|i| u8::from_str_radix(&s[i..i + 2], 16).unwrap())
            .collect()
    };
    (
        CertificateDer::from(hex("RETRY_E2E_CERT")),
        PrivatePkcs8KeyDer::from(hex("RETRY_E2E_KEY")),
    )
}

fn generate_cert() {
    let cert = rcgen::generate_simple_self_signed(vec!["localhost".into()]).unwrap();
    let hex = |bytes: &[u8]| bytes.iter().map(|b| format!("{b:02x}")).collect::<String>();
    // SAFETY: single-threaded at this point
    unsafe {
        std::env::set_var("RETRY_E2E_CERT", hex(cert.cert.der()));
        std::env::set_var("RETRY_E2E_KEY", hex(&cert.signing_key.serialize_der()));
    }
}

fn cpu_ns() -> u64 {
    let mut usage: libc::rusage = unsafe { std::mem::zeroed() };
    assert_eq!(unsafe { libc::getrusage(libc::RUSAGE_SELF, &mut usage) }, 0);
    let ns = |t: libc::timeval| t.tv_sec as u64 * 1_000_000_000 + t.tv_usec as u64 * 1_000;
    ns(usage.ru_utime) + ns(usage.ru_stime)
}

fn set_buffers(sock: &UdpSocket) {
    let sock = socket2::SockRef::from(sock);
    let kb: usize = std::env::var("RETRY_E2E_RCVBUF_KB")
        .map(|n| n.parse().unwrap())
        .unwrap_or(256);
    sock.set_recv_buffer_size(kb << 10).unwrap();
    // Linux silently caps at net.core.rmem_max, and reports double the size set
    let mut actual = sock.recv_buffer_size().unwrap();
    if cfg!(target_os = "linux") {
        actual /= 2;
    }
    if actual < kb << 10 {
        eprintln!(
            "WARN receive buffer capped at {} KiB, wanted {kb} KiB",
            actual >> 10
        );
    }
}

#[cfg(feature = "filter")]
struct RetryStrangers;

#[cfg(feature = "filter")]
impl quinn::InitialFilter for RetryStrangers {
    fn after_token_check(
        &self,
        _: &quinn::InitialMetadata,
        token: &quinn::TokenCheck,
    ) -> quinn::InitialDecision {
        match token.remote_address_validated() {
            true => quinn::InitialDecision::Proceed,
            false => quinn::InitialDecision::Retry,
        }
    }
}

fn server(mode: &str, workers: usize, bind: &str) {
    let standalone = std::env::var("RETRY_E2E_CERT").is_err();
    if standalone {
        generate_cert();
    }
    let rt = tokio::runtime::Builder::new_multi_thread()
        .worker_threads(workers)
        .enable_all()
        .build()
        .unwrap();
    let (cert, key) = cert();
    // Only the `filter` build changes it
    #[allow(unused_mut)]
    let mut config = quinn::ServerConfig::with_single_cert(vec![cert], key.into()).unwrap();
    match mode {
        "manual" => {}
        #[cfg(feature = "filter")]
        "fast" | "fast-mac" => {
            config.initial_filter(Arc::new(RetryStrangers));
        }
        #[cfg(feature = "filter")]
        "manual-mac" => {}
        _ => panic!("mode {mode} unsupported by this build"),
    }
    #[cfg(feature = "filter")]
    if mac(mode) {
        let key = ring::hmac::Key::new(ring::hmac::HMAC_SHA256, &[7; 32]);
        config.token_authentication_key(Some(Arc::new(key)));
    }
    let sock = UdpSocket::bind(bind).unwrap();
    set_buffers(&sock);
    let addr = sock.local_addr().unwrap();
    let endpoint = {
        let _guard = rt.enter();
        quinn::Endpoint::new(
            Default::default(),
            Some(config),
            sock,
            Arc::new(quinn::TokioRuntime),
        )
        .unwrap()
    };
    let accept = endpoint.clone();
    rt.spawn(async move {
        while let Some(incoming) = accept.accept().await {
            if incoming.remote_address_validated() {
                // Only the smoke test's retried client gets here
                tokio::spawn(async move {
                    if let Ok(conn) = incoming.await {
                        conn.closed().await;
                    }
                });
            } else {
                incoming.retry().unwrap();
            }
        }
    });
    println!("READY {addr}");
    std::io::stdout().flush().unwrap();
    if standalone {
        // Started by hand: report CPU use until killed
        let mut last = (Instant::now(), cpu_ns());
        loop {
            thread::sleep(Duration::from_secs(1));
            let now = (Instant::now(), cpu_ns());
            let cores = (now.1 - last.1) as f64 / now.0.duration_since(last.0).as_nanos() as f64;
            println!("CPU {:.0}% of a core", cores * 100.0);
            last = now;
        }
    }
    for line in std::io::stdin().lock().lines() {
        match line.unwrap().as_str() {
            "CPU" => println!("CPU {}", cpu_ns()),
            other => panic!("unknown request {other}"),
        }
        std::io::stdout().flush().unwrap();
    }
}

/// Client Initials with unique source CIDs, and those CIDs' indices
fn corpus(
    mode: &str,
    kind: &str,
    addr: SocketAddr,
    count: usize,
) -> (Vec<Vec<u8>>, HashMap<Vec<u8>, usize>) {
    let (cert, _) = cert();
    let mut roots = rustls::RootCertStore::empty();
    roots.add(cert).unwrap();
    let mut config = quinn::ClientConfig::with_root_certificates(Arc::new(roots)).unwrap();
    let store = Arc::new(proto::TokenMemoryCache::default());
    config.token_store(store.clone());
    let mut endpoint = proto::Endpoint::new(Default::default(), None, true);
    let now = Instant::now();
    let mut packets = Vec::new();
    let mut ids = HashMap::new();
    for id in 0..count {
        if kind == "bogus" {
            let mut token = vec![7; if mac(mode) { 72 } else { 80 }];
            if mac(mode) {
                // Version and Retry type bytes, so the token reaches the MAC check
                token[..2].copy_from_slice(&[1, 0]);
            }
            proto::TokenStore::insert(&*store, "localhost", token.into());
        }
        let (_, mut conn) = endpoint
            .connect(now, config.clone(), addr, "localhost")
            .unwrap();
        let mut packet = Vec::new();
        assert!(conn.poll_transmit(now, 1, &mut packet).is_some());
        assert_eq!(packet.len(), 1200);
        let dcid_len = packet[5] as usize;
        let scid_len = packet[6 + dcid_len] as usize;
        let scid = packet[7 + dcid_len..7 + dcid_len + scid_len].to_vec();
        assert!(ids.insert(scid, id).is_none());
        packets.push(packet);
    }
    (packets, ids)
}

fn client(mode: &str, workers: usize, kind: &str, window: usize) {
    let n: usize = std::env::var("RETRY_E2E_N")
        .map(|n| n.parse().unwrap())
        .unwrap_or(32768);
    assert_eq!(n % window, 0);
    generate_cert();
    let wrap = std::env::var("RETRY_E2E_SERVER_WRAP").unwrap_or_default();
    let mut wrap = wrap.split_whitespace();
    let exe = std::env::current_exe().unwrap();
    let mut child = match wrap.next() {
        Some(program) => {
            let mut command = Command::new(program);
            command.args(wrap).arg(exe);
            command
        }
        None => Command::new(exe),
    };
    let mut child = child
        .args(["server", mode, &workers.to_string()])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .spawn()
        .unwrap();
    let mut to_server = child.stdin.take().unwrap();
    let mut from_server = BufReader::new(child.stdout.take().unwrap());
    let mut line = String::new();
    from_server.read_line(&mut line).unwrap();
    let addr: SocketAddr = line.strip_prefix("READY ").unwrap().trim().parse().unwrap();
    let mut server_cpu = || {
        writeln!(to_server, "CPU").unwrap();
        to_server.flush().unwrap();
        let mut line = String::new();
        from_server.read_line(&mut line).unwrap();
        line.strip_prefix("CPU ")
            .unwrap()
            .trim()
            .parse::<u64>()
            .unwrap()
    };

    smoke(addr);
    let (packets, ids) = corpus(mode, kind, addr, CORPUS);
    let sock = UdpSocket::bind("127.0.0.1:0").unwrap();
    set_buffers(&sock);
    sock.connect(addr).unwrap();
    sock.set_read_timeout(Some(Duration::from_secs(2))).unwrap();
    let mut buf = [0; 2048];
    let mut wall = Vec::new();
    let mut cpu = Vec::new();
    let mut rtts = Vec::new();
    for sample in 0..=SAMPLES {
        // Sample 0 warms up
        let count = if sample == 0 { CORPUS } else { n };
        let cpu_start = server_cpu();
        let start = Instant::now();
        for base in (0..count).step_by(window) {
            let mut sent_at = Vec::with_capacity(window);
            for j in 0..window {
                sent_at.push(Instant::now());
                sock.send(&packets[(base + j) % CORPUS]).unwrap();
            }
            let mut seen = vec![false; window];
            for _ in 0..window {
                let len = sock.recv(&mut buf).expect("missing Retry");
                let received = Instant::now();
                assert_eq!(buf[0] & 0xf0, 0xf0, "expected a Retry");
                let dcid = &buf[6..6 + buf[5] as usize];
                assert!(len > 6 + dcid.len());
                let j = (ids[dcid] + CORPUS - base % CORPUS) % CORPUS;
                assert!(j < window && !seen[j], "unexpected or duplicate Retry");
                seen[j] = true;
                if sample != 0 {
                    rtts.push(received.duration_since(sent_at[j]).as_nanos() as u64);
                }
            }
        }
        let elapsed = start.elapsed();
        let cpu_used = server_cpu() - cpu_start;
        if sample != 0 {
            wall.push(elapsed.as_nanos() as f64 / count as f64);
            cpu.push(cpu_used as f64 / count as f64);
        }
    }
    drop(to_server);
    child.wait().unwrap();
    let median = |v: &mut Vec<f64>| {
        v.sort_by(f64::total_cmp);
        v[v.len() / 2]
    };
    rtts.sort_unstable();
    println!(
        "RESULT mode={mode} workers={workers} kind={kind} window={window} n={n} \
         wall_ns={:.0} rate_k={:.1} server_cpu_ns={:.0} p50_rtt_us={:.1} p99_rtt_us={:.1} \
         wall={wall:.0?} cpu={cpu:.0?}",
        median(&mut wall.clone()),
        1e6 / median(&mut wall.clone()),
        median(&mut cpu.clone()),
        rtts[rtts.len() / 2] as f64 / 1e3,
        rtts[rtts.len() * 99 / 100] as f64 / 1e3,
    );
}

/// A real client completes a handshake through the server's Retry
fn smoke(addr: SocketAddr) {
    let rt = tokio::runtime::Builder::new_current_thread()
        .enable_all()
        .build()
        .unwrap();
    rt.block_on(async {
        let (cert, _) = cert();
        let mut roots = rustls::RootCertStore::empty();
        roots.add(cert).unwrap();
        let client = quinn::Endpoint::client("127.0.0.1:0".parse().unwrap()).unwrap();
        client.set_default_client_config(
            quinn::ClientConfig::with_root_certificates(Arc::new(roots)).unwrap(),
        );
        let conn = tokio::time::timeout(
            Duration::from_secs(5),
            client.connect(addr, "localhost").unwrap(),
        )
        .await
        .expect("smoke handshake timed out")
        .unwrap();
        conn.close(0u32.into(), b"smoke");
        client.wait_idle().await;
    });
}

/// Sends unique Initials at each rate and counts the Retries that come back
fn flood(server: &str, kind: &str, rates: &[String]) {
    let env = |name, default: usize| std::env::var(name).map_or(default, |v| v.parse().unwrap());
    let threads = env("RETRY_E2E_THREADS", 4);
    let secs = env("RETRY_E2E_STEP_SECS", 5) as u64;
    let addr = server.to_socket_addrs().unwrap().next().unwrap();
    // The certificate only matters for completing a handshake, which a flood never does
    generate_cert();
    let (mode, kind) = match kind.strip_suffix("-mac") {
        Some(kind) => ("fast-mac", kind),
        None => ("fast", kind),
    };
    let packets = Arc::new(corpus(mode, kind, addr, FLOOD_CORPUS).0);
    for rate in rates {
        let rate: f64 = rate.parse::<f64>().unwrap() * 1000.0;
        let (sent, retries) = flood_step(addr, &packets, threads, rate, secs);
        println!(
            "RESULT kind={kind} mac={} rate_k={:.0} sent_k={:.1} retries_k={:.1} answered={:.3}",
            mode == "fast-mac",
            rate / 1e3,
            sent / 1e3,
            retries / 1e3,
            retries / sent,
        );
    }
}

/// Sent and Retry rates over `secs`, after one second of warm-up
fn flood_step(
    addr: SocketAddr,
    packets: &Arc<Vec<Vec<u8>>>,
    threads: usize,
    rate: f64,
    secs: u64,
) -> (f64, f64) {
    let stop = Arc::new(AtomicBool::new(false));
    let start = Instant::now();
    let mut counters = Vec::new();
    let mut handles = Vec::new();
    for t in 0..threads {
        let bind = if addr.is_ipv6() {
            "[::]:0"
        } else {
            "0.0.0.0:0"
        };
        let sock = UdpSocket::bind(bind).unwrap();
        set_buffers(&sock);
        sock.connect(addr).unwrap();
        let rx = sock.try_clone().unwrap();
        rx.set_read_timeout(Some(Duration::from_millis(100)))
            .unwrap();
        let (sent, received) = (Arc::new(AtomicU64::new(0)), Arc::new(AtomicU64::new(0)));
        counters.push((sent.clone(), received.clone()));

        let stop_rx = stop.clone();
        handles.push(thread::spawn(move || {
            let mut buf = [0; 2048];
            while !stop_rx.load(Ordering::Relaxed) {
                if let Ok(len) = rx.recv(&mut buf) {
                    if len > 0 && buf[0] & 0xf0 == 0xf0 {
                        received.fetch_add(1, Ordering::Relaxed);
                    }
                }
            }
        }));

        let (stop, packets) = (stop.clone(), packets.clone());
        let per_thread = rate / threads as f64;
        handles.push(thread::spawn(move || {
            // This thread's share of the corpus: t, t + threads, ...
            let (mut n, mut i) = (0u64, t);
            while !stop.load(Ordering::Relaxed) {
                let due = (start.elapsed().as_secs_f64() * per_thread) as u64;
                if n >= due {
                    thread::sleep(Duration::from_micros(50));
                    continue;
                }
                // Bounded, so a client that falls behind still sees `stop`
                for _ in 0..(due - n).min(256) {
                    // Send errors (e.g. ENOBUFS) just show up as a lower sent rate
                    if sock.send(&packets[i]).is_ok() {
                        sent.fetch_add(1, Ordering::Relaxed);
                    }
                    n += 1;
                    i += threads;
                    if i >= packets.len() {
                        i = t;
                    }
                }
            }
        }));
    }
    let totals = || {
        counters.iter().fold((0, 0), |(s, r), (sent, received)| {
            (
                s + sent.load(Ordering::Relaxed),
                r + received.load(Ordering::Relaxed),
            )
        })
    };
    thread::sleep(Duration::from_secs(1));
    let (t0, (s0, r0)) = (Instant::now(), totals());
    thread::sleep(Duration::from_secs(secs));
    let (t1, (s1, r1)) = (Instant::now(), totals());
    stop.store(true, Ordering::Relaxed);
    for handle in handles {
        handle.join().unwrap();
    }
    // Let the server drain before the next step
    thread::sleep(Duration::from_secs(1));
    let elapsed = t1.duration_since(t0).as_secs_f64();
    ((s1 - s0) as f64 / elapsed, (r1 - r0) as f64 / elapsed)
}
